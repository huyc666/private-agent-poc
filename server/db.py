_POOLS: dict[str, ConnectionPool] = {}
_INITIALIZED_URLS: set[str] = set()
_PRAGMA_TABLE_RE = re.compile(
    r"^\s*PRAGMA\s+table_info\((?P<table>\w+)\)\s*$", re.I)
_REPLACE_RE = re.compile(
    r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+(?P<table>\w+)\s*\((?P<columns>[^)]+)\)",
    re.I | re.S)


def _database_url(database: str) -> str:
    if database == "state":
        url = config.STATE_DATABASE_URL or config.DATABASE_URL
    elif database == "usage":
        url = config.USAGE_DATABASE_URL or config.DATABASE_URL
    else:
        raise RuntimeError("未知业务数据库")
    if not url:
        raise RuntimeError("PostgreSQL 连接失败")
    return url


def _backend(database: str) -> str:
    backend = (config.STATE_BACKEND if database == "state"
               else config.USAGE_BACKEND)
    backend = (backend or "sqlite").lower()
    if backend not in ("sqlite", "postgres"):
        raise RuntimeError("数据库后端配置无效")
    return backend


def _path(database: str) -> Path:
    path = Path(config.STATE_DB if database == "state" else config.USAGE_DB)
    path.parent.mkdir(parents=True, exist_ok=True)
    return path


def ensure_postgres_schema(connection: psycopg.Connection) -> None:
    """初始化全部业务表；DDL 幂等，可供应用连接与迁移工具共用。"""
    with connection.cursor() as cursor:
        for statement in filter(None, PG_DDL.split(";")):
            cursor.execute(statement)


def _mark_schema_initialized(connection: psycopg.Connection, url: str) -> None:
    if url not in _INITIALIZED_URLS:
        ensure_postgres_schema(connection)
        connection.commit()
        _INITIALIZED_URLS.add(url)


def _pool(url: str) -> ConnectionPool:
    pool = _POOLS.get(url)
    if pool is None:
        pool = ConnectionPool(
            url, min_size=1, max_size=8, timeout=5, open=True)
        _POOLS[url] = pool
    return pool


def connect(database: str) -> sqlite3.Connection | _PostgresConnection:
    if _backend(database) == "sqlite":
        connection = sqlite3.connect(str(_path(database)))
        connection.execute("PRAGMA journal_mode=WAL")
        connection.execute("PRAGMA busy_timeout=3000")
        return connection
    url = _database_url(database)
    try:
        raw = _pool(url).getconn()
        _mark_schema_initialized(raw, url)
        return _PostgresConnection(raw, url)
    except RuntimeError:
        raise
    except Exception:
        raise RuntimeError("PostgreSQL 连接失败") from None


def close_pools() -> None:
    """关闭所有业务 PG 连接池；主要供进程退出与集成测试清理使用。"""
    global _POOLS
    pools = list(_POOLS.values())
    _POOLS.clear()
    _INITIALIZED_URLS.clear()
    for pool in pools:
        with contextlib.suppress(Exception):
            pool.close()


def is_postgres(connection: sqlite3.Connection | _PostgresConnection) -> bool:
    return isinstance(connection, _PostgresConnection)


def _translate_replace(sql: str) -> str:
    match = _REPLACE_RE.match(sql)
    if not match:
        return sql
    table = match.group("table")
    columns = [column.strip() for column in match.group("columns").split(",")]
    if not columns:
        return sql
    updates = ", ".join(
        f"{column}=EXCLUDED.{column}" for column in columns[1:])
    action = f"ON CONFLICT ({columns[0]}) DO UPDATE SET {updates}"
    return f"{sql.rstrip()} {action}"


def translate_sql(sql: str, *, postgres: bool = False) -> str:
    if not postgres:
        return sql
    pragma = _PRAGMA_TABLE_RE.match(sql)
    if pragma:
        return (
            "SELECT column_name FROM information_schema.columns"
            " WHERE table_schema = current_schema() AND table_name = %s")
    sql = _translate_replace(sql)
    if re.match(r"^\s*BEGIN(\s+IMMEDIATE)?\s*$", sql, re.I):
        return "SELECT 1"
    if re.search(r"\bINSERT\s+OR\s+IGNORE\b", sql, re.I):
        sql = re.sub(r"\bINSERT\s+OR\s+IGNORE\b", "INSERT", sql, flags=re.I)
        sql += " ON CONFLICT DO NOTHING"
    sql = sql.replace("?", "%s")
    return sql


class _DictRow(dict):
    def __init__(self, values: Sequence[Any], columns: Sequence[str]):
        super().__init__(zip(columns, values))
        self._values = tuple(values)

    def __int__(self) -> int:
        return len(self._values)

    def __index__(self) -> int:
        return len(self._values)

    def __len__(self) -> int:
        return len(self._values)

    def __getitem__(self, key):
        if isinstance(key, slice):
            return self._values[key]
        if isinstance(key, int):
            return self._values[key]
        return super().__getitem__(key)

    def __iter__(self):
        return iter(self._values)

    def __eq__(self, other):
        if isinstance(other, tuple):
            return self._values == other
        return super().__eq__(other)


def _row_factory(cursor: psycopg.Cursor) -> _DictRow | None:
    values = cursor.fetchone()
    if values is None:
        return None
    columns = [description[0] for description in cursor.description or []]
    return _DictRow(values, columns)


class _PostgresCursor:
    def __init__(self, cursor: psycopg.Cursor):
        self._cursor = cursor

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount

    @property
    def description(self):
        return self._cursor.description

    def execute(self, sql: str, params: Sequence[Any] | None = None):
        translated = translate_sql(sql, postgres=True)
        if _PRAGMA_TABLE_RE.match(sql):
            table = _PRAGMA_TABLE_RE.match(sql).group("table")
            self._cursor.execute(translated, (table,))
        else:
            self._cursor.execute(translated, params)
        return self

    def executemany(self, sql: str,
                    params: Iterable[Sequence[Any]]) -> None:
        self._cursor.executemany(translate_sql(sql, postgres=True), params)

    def fetchone(self) -> _DictRow | None:
        return _row_factory(self._cursor)

    def fetchall(self) -> list[_DictRow]:
        if not self._cursor.description:
            return []
        columns = [description[0] for description in self._cursor.description]
        return [
            _DictRow(row, columns)
            for row in self._cursor.fetchall()
        ]

    def close(self) -> None:
        self._cursor.close()

    def __iter__(self):
        while True:
            row = self.fetchone()
            if row is None:
                return
            yield row

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.close()


class _PostgresConnection:
    def __init__(self, connection: psycopg.Connection, url: str):
        self._connection = connection
        self._url = url
        self._row_factory = _row_factory
        self._total_changes = 0

    @property
    def row_factory(self):
        return self._row_factory

    @row_factory.setter
    def row_factory(self, value) -> None:
        if value is not sqlite3.Row:
            self._row_factory = _row_factory

    @property
    def isolation_level(self):
        return None

    @isolation_level.setter
    def isolation_level(self, value) -> None:
        pass

    @property
    def total_changes(self) -> int:
        return self._total_changes

    def _cursor(self) -> psycopg.Cursor:
        return self._connection.cursor()

    def execute(self, sql: str,
                params: Sequence[Any] | None = None) -> _PostgresCursor:
        cursor = self._cursor()
        wrapper = _PostgresCursor(cursor)
        try:
            wrapper.execute(sql, params)
            self._total_changes += max(wrapper.rowcount, 0)
            return wrapper
        except Exception:
            cursor.close()
            raise

    def executemany(self, sql: str,
                    params: Iterable[Sequence[Any]]) -> _PostgresCursor:
        raw = self._connection.cursor()
        wrapper = _PostgresCursor(raw)
        try:
            wrapper.executemany(sql, params)
            self._total_changes += max(wrapper.rowcount, 0)
            return wrapper
        except Exception:
            raw.close()
            raise

    def cursor(self) -> _PostgresCursor:
        return _PostgresCursor(self._cursor())

    def commit(self) -> None:
        self._connection.commit()

    def rollback(self) -> None:
        self._connection.rollback()

    def close(self) -> None:
        try:
            self._connection.rollback()
        finally:
            pool = _POOLS.get(self._url)
            if pool is not None:
                pool.putconn(self._connection)
            else:
                self._connection.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        if exc_type is None:
            self.commit()
        else:
            self.rollback()
        self.close()


def execute(connection: sqlite3.Connection | _PostgresConnection,
            sql: str, params: Sequence[Any] | None = None):
    if not is_postgres(connection):
        return connection.execute(sql, params or ())
    return connection.execute(sql, params)
